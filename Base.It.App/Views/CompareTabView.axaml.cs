    private CompareTabViewModel? _vm;

    /// <summary>Above this many lines the row-aligned renderer (one control
    /// per line × both sides) would spawn too many controls; fall back to the
    /// lighter flowing renderer.</summary>
    private const int AlignedMaxLines = 2000;

    public CompareTabView()
    {
        // InitializeComponent (generated by the Avalonia name source generator)
        // loads the XAML AND assigns the named PanesHost field. AvaloniaXamlLoader.Load
        // alone does not populate generated fields.
        InitializeComponent();
        DataContextChanged += (_, _) => Bind();
        DetachedFromVisualTree += (_, _) => Unbind();
    }

    /// <summary>Export this comparison (Line column + one per environment) to CSV.</summary>
    private async void OnExportCsvClick(object? sender, Avalonia.Interactivity.RoutedEventArgs e)
    {
        if (DataContext is not CompareTabViewModel vm) return;
        await Services.CsvExport.SaveAsync(this, vm, vm.Toasts);
    }

    private void Bind()
    {
        Unbind();
        _vm = DataContext as CompareTabViewModel;
        if (_vm is null) return;
        _vm.Panes.CollectionChanged += OnPanesChanged;
        _vm.PropertyChanged         += OnVmPropertyChanged;
        Rebuild();
    }

    private void Unbind()
    {
        if (_vm is null) return;
        _vm.Panes.CollectionChanged -= OnPanesChanged;
        _vm.PropertyChanged         -= OnVmPropertyChanged;
        _vm = null;
    }

    private void OnPanesChanged(object? s, NotifyCollectionChangedEventArgs e) => Rebuild();
    private void OnVmPropertyChanged(object? s, PropertyChangedEventArgs e)
    {
        if (e.PropertyName == nameof(CompareTabViewModel.ExpandedPane)) Rebuild();
    }

    private void Rebuild()
    {
        if (_vm is null || PanesHost is null) return;

        PanesHost.Children.Clear();
        PanesHost.ColumnDefinitions.Clear();

        var panes = _vm.ExpandedPane is { } exp ? new[] { exp } : _vm.Panes.ToArray();
        if (panes.Length == 0) return;

        PanesHost.ColumnDefinitions.Add(new ColumnDefinition(1, GridUnitType.Star));

        // Two environments (not expanded) → git-style row-aligned side-by-side.
        // One (expanded) or 3+ → the N-pane AvaloniaEdit editor view (syntax
        // highlighting, find, scroll-sync) — the same robust editors as the
        // preview, instead of the old flowing text blocks.
        Control view =
            panes.Length == 2 && Math.Max(panes[0].Lines.Count, panes[1].Lines.Count) <= AlignedMaxLines
                ? BuildAlignedTwoPane(panes[0], panes[1])
                : BuildMultiPane(panes);
        Grid.SetColumn(view, 0);
        PanesHost.Children.Add(view);
    }

    /// <summary>N-pane (1 or 3+) view: per-pane [label + copy + expand] headers
    /// above the shared multi-editor body.</summary>
    private Control BuildMultiPane(EnvPane[] panes)
    {
        var isDark = Application.Current?.ActualThemeVariant == Avalonia.Styling.ThemeVariant.Dark;
        var built = SqlDiffEditor.BuildMulti(panes, isDark, _vm?.IgnoreWhitespace ?? false);
        var body = built.Body;

        var header = new Grid();
        for (int i = 0; i < panes.Length; i++)
        {
            header.ColumnDefinitions.Add(new ColumnDefinition(1, GridUnitType.Star));
            if (i < panes.Length - 1) header.ColumnDefinitions.Add(new ColumnDefinition(GridLength.Auto));

            Control h = BuildHeader(panes[i]);
            // Per-target change navigator (each non-base column), like the 2-pane view.
            if (i < built.Panes.Count && !built.Panes[i].IsBase && built.Panes[i].Hunks.Count > 0)
            {
                var dock = new DockPanel { LastChildFill = true };
                var nav = SqlDiffEditor.BuildPaneNavigator(built.Panes[i]);
                DockPanel.SetDock(nav, Dock.Right);
                dock.Children.Add(nav);
                dock.Children.Add(h);
                h = dock;
            }
            Grid.SetColumn(h, i * 2);
            header.Children.Add(h);
        }

        var outer = new Border
        {
            CornerRadius = new CornerRadius(6),
            BorderBrush = Application.Current!.TryGetResource(
                "ControlStrokeColorDefaultBrush", out var br) ? br as IBrush : Brushes.Gray,
            BorderThickness = new Thickness(1),
            ClipToBounds = true,
            Child = new Grid { RowDefinitions = new RowDefinitions("Auto,*") },
        };
        var grid = (Grid)outer.Child;
        Grid.SetRow(header, 0);
        Grid.SetRow(body, 1);
        grid.Children.Add(header);
        grid.Children.Add(body);
        return outer;
    }

    /// <summary>
    /// Git-style 2-pane view: the two per-pane headers side by side above the
    /// shared row-aligned body from <see cref="AlignedDiffView"/> (which owns
    /// its own single scroll viewer, so no SharedScrollOffset sync is needed
    /// and there's no click-scroll-reset).
    /// </summary>
    private Control BuildAlignedTwoPane(EnvPane left, EnvPane right)
    {
        var header = new Grid { ColumnDefinitions = new ColumnDefinitions("*,*") };
        var lh = BuildHeader(left);
        var rh = BuildHeader(right);
        Grid.SetColumn(lh, 0);
        Grid.SetColumn(rh, 1);
        header.Children.Add(lh);
        header.Children.Add(rh);

        var isDark = Application.Current?.ActualThemeVariant == Avalonia.Styling.ThemeVariant.Dark;
        var built = SqlDiffEditor.Build(left, right, isDark);

        var outer = new Border
        {
            CornerRadius = new CornerRadius(6),
            BorderBrush = Application.Current!.TryGetResource(
                "ControlStrokeColorDefaultBrush", out var br) ? br as IBrush : Brushes.Gray,
            BorderThickness = new Thickness(1),
            ClipToBounds = true,
            Child = new Grid { RowDefinitions = new RowDefinitions("Auto,*") },
        };
        var grid = (Grid)outer.Child;
        Grid.SetRow(header, 0);
        Grid.SetRow(built.Body, 1);
        grid.Children.Add(header);
        grid.Children.Add(built.Body);
        return outer;
    }

    private Control BuildPane(EnvPane pane)
    {
        var header = BuildHeader(pane);

        var text = new SelectableTextBlock
        {
            FontFamily = new FontFamily("Cascadia Mono,Consolas,monospace"),
            FontSize = 12,
            TextWrapping = TextWrapping.NoWrap,
            Padding = new Thickness(10, 6),
            Background = Brushes.Transparent
        };
        PopulateInlines(text, pane.Lines);

        var scroll = new ScrollViewer
        {
            HorizontalScrollBarVisibility = Avalonia.Controls.Primitives.ScrollBarVisibility.Auto,
            VerticalScrollBarVisibility   = Avalonia.Controls.Primitives.ScrollBarVisibility.Auto,
            Content = text
        };
        scroll.Bind(ScrollViewer.OffsetProperty, new Binding(nameof(CompareTabViewModel.SharedScrollOffset))
        {
            Source = _vm,
            Mode = BindingMode.TwoWay
        });

        // Line-number gutter pinned to the left of the code, sharing its
        // vertical scroll (see DiffPaneGutter).
        var body = DiffPaneGutter.Wrap(scroll, pane.Lines.Count);

        var outer = new Border
        {
            CornerRadius = new CornerRadius(6),
            BorderBrush = Application.Current!.TryGetResource(
                "ControlStrokeColorDefaultBrush", out var br) ? br as IBrush : Brushes.Gray,
            BorderThickness = new Thickness(1),
            ClipToBounds = true,
            Child = new Grid { RowDefinitions = new RowDefinitions("Auto,*") }
        };
        var grid = (Grid)outer.Child;
        Grid.SetRow(header, 0);
        Grid.SetRow(body, 1);
        grid.Children.Add(header);
        grid.Children.Add(body);
        return outer;
    }

