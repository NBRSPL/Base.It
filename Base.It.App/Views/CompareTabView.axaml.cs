    private static void PopulateInlines(SelectableTextBlock target, IReadOnlyList<AlignedPaneLine> lines)
    {
        target.Inlines?.Clear();
        if (target.Inlines is null) target.Inlines = new InlineCollection();

        // Theme-aware diff colours so changed lines stay legible in
        // both modes. Falls back to a high-contrast hardcoded pair if
        // the theme tokens haven't loaded yet (e.g. during startup
        // before App.DiffBgBrush has been resolved). Colours match
        // PaneDiffView so the two "compare two objects" surfaces render
        // identically.
        var diffBg = ResolveBrush("App.DiffBgBrush",    new SolidColorBrush(Color.FromArgb(0xFF, 0x7A, 0x5A, 0x00)));
        var diffFg = ResolveBrush("App.DiffFgBrush",    new SolidColorBrush(Color.FromArgb(0xFF, 0xFF, 0xF4, 0xC2)));
        var delBg  = ResolveBrush("App.DiffDelBgBrush", new SolidColorBrush(Color.FromArgb(0xFF, 0x5C, 0x23, 0x33)));
        var delFg  = ResolveBrush("App.DiffDelFgBrush", new SolidColorBrush(Color.FromArgb(0xFF, 0xFF, 0xB3, 0xB3)));
        var addBg  = ResolveBrush("App.DiffAddBgBrush", new SolidColorBrush(Color.FromArgb(0xFF, 0x21, 0x39, 0x2B)));
        var addFg  = ResolveBrush("App.DiffAddFgBrush", new SolidColorBrush(Color.FromArgb(0xFF, 0xB6, 0xF0, 0xB6)));

        for (int i = 0; i < lines.Count; i++)
        {
            var line = lines[i];

            // 2-pane mode: char-level segments from AlignPair → paint only
            // the changed substrings (Removed on the A side, Added on the B
            // side; Equal spans stay plain). This is the git / VS-Code-style
            // highlight the whole engine change is for.
            if (line.Segments is { Count: > 0 } segments)
            {
                foreach (var seg in segments)
                {
                    var (bg, fg) = seg.Kind switch
                    {
                        CharDiff.SegmentKind.Removed => ((IBrush?)delBg, (IBrush?)delFg),
                        CharDiff.SegmentKind.Added   => ((IBrush?)addBg, (IBrush?)addFg),
                        _                            => ((IBrush?)null,  (IBrush?)null),
                    };
                    AddRun(target.Inlines!, seg.Text, bg, fg);
                }
            }
            else
            {
                // N-way (3+ env) fallback: whole-line amber when Different.
                if (line.State == LineState.Different)
                    AddRun(target.Inlines!, line.Text, diffBg, diffFg);
                else
                    AddRun(target.Inlines!, line.Text, null, null);
            }

            if (i < lines.Count - 1) target.Inlines.Add(new LineBreak());
        }
    }

    private static void AddRun(InlineCollection target, string text, IBrush? bg, IBrush? fg)
    {
        // A zero-length run still needs to exist for empty lines so the
        // LineBreak cadence stays aligned across panes.
        var run = new Run(text);
        if (bg is not null) { run.Background = bg; run.FontWeight = FontWeight.SemiBold; }
        if (fg is not null) run.Foreground = fg;
        target.Add(run);
    }

    /// <summary>Per-column diff indicator for the N-way view (mirrors
    /// <see cref="PaneDiffView"/>): "base" on the base column, "in sync" on an
    /// unchanged environment, and a red "≠ N" pill (with a +/−/~ breakdown
    /// tooltip) on any environment that differs from the base.</summary>
    private static Control? BuildDiffBadge(MultiDiffBadge? badge)
    {
        if (badge is null) return null;
        if (badge.IsBase) return MutedChip("base", "The base — every other column is compared against this");
        if (!badge.Differs) return MutedChip("in sync", "Identical to the base");

        var red = ResolveBrush("App.DiffDelGutterBrush", new SolidColorBrush(Color.FromRgb(0xED, 0x1C, 0x24)));
        var chip = new Border
        {
            Background = red, CornerRadius = new CornerRadius(4),
            Padding = new Thickness(6, 1), VerticalAlignment = VerticalAlignment.Center,
            Child = new TextBlock
            {
                Text = $"≠ {badge.Total}", Foreground = Brushes.White,
                FontSize = 10, FontWeight = FontWeight.SemiBold,
            },
        };
        ToolTip.SetTip(chip, $"+{badge.Added} added · −{badge.Removed} removed · ~{badge.Changed} changed (vs base)");
        return chip;
    }

    private static Border MutedChip(string text, string tip)
    {
        var chip = new Border
        {
            Background = Brushes.Transparent,
            BorderBrush = ResolveBrush("App.StrokeBrush", Brushes.Gray),
            BorderThickness = new Thickness(1),
            CornerRadius = new CornerRadius(4),
            Padding = new Thickness(6, 1), VerticalAlignment = VerticalAlignment.Center,
            Child = new TextBlock { Text = text, Opacity = 0.7, FontSize = 10, FontWeight = FontWeight.SemiBold },
        };
        ToolTip.SetTip(chip, tip);
        return chip;
    }

    private static IBrush ResolveBrush(string key, IBrush fallback)
        => Application.Current!.TryGetResource(key, null, out var r) && r is IBrush b ? b : fallback;
}
